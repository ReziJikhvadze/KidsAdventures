using AdventurePacks.Api.Domain.Enums;

namespace AdventurePacks.Api.Services.Story;

/// <summary>
/// Three ready-made causal chains per world, one of which a V3 book follows.
///
/// Each is eight steps where every step is the physical consequence of the one before it. That
/// property is the whole point: books were coming back as eight scenes that could be shuffled
/// without loss — four crossings of the same stream, a slideshow rather than a story. A chain
/// cannot be shuffled, because step five only makes sense after step four.
///
/// The cost is worth saying plainly. Eighteen chains is eighteen plots, and a family collecting a
/// series will meet one twice. This is a variant to be measured against V1 and V2, not a
/// settlement.
///
/// The branch is chosen here rather than by the model. Asked to pick one of three, a model picks
/// the first far more often than a third of the time, and the whole reason for having three is
/// that consecutive books should differ.
/// </summary>
public static class StoryBranches
{
    public sealed record Branch
    {
        public required string Name { get; init; }

        /// <summary>Eight steps, each the consequence of the previous.</summary>
        public required IReadOnlyList<string> Chain { get; init; }
    }

    /// <summary>
    /// Picks a chain. The seed is the run's id, so the same book replays identically and two books
    /// made a second apart do not land on the same plot.
    /// </summary>
    public static Branch For(ThemeType theme, Guid seed)
    {
        var branches = All(theme);
        var index = Math.Abs(seed.GetHashCode()) % branches.Count;
        return branches[index];
    }

